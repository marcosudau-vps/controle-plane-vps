import hashlib
import json
from pathlib import Path

from sqlalchemy.orm import Session

from . import models
from .caddy_protection import resolve_route_protection
from .config import get_settings
from .domains import render_domain_value


MANAGED_HEADER = "# Generated by Control Plane. Do not edit manually.\n"


def _write(path: Path, content: str) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def generate_caddy(db: Session) -> dict:
    settings = get_settings()
    routes = db.query(models.Route).filter(models.Route.status == "active").order_by(models.Route.host, models.Route.path).all()
    lines = [MANAGED_HEADER.rstrip(), ""]
    if settings.caddy_protection_enabled:
        lines.extend(
            [
                "(caddy_schutz_forward_auth) {",
                "    forward_auth 127.0.0.1:8765 {",
                "        uri /caddy-schutz/check",
                "        copy_headers Set-Cookie",
                "    }",
                "}",
                "",
            ]
        )
    for route in routes:
        path_part = "" if route.path == "/" else f" {route.path}*"
        host = render_domain_value(route.host)
        protected = settings.caddy_protection_enabled and resolve_route_protection(db, route)
        lines.extend(
            [
                f"# provisional development domain rendered from template `{route.host}`. Change CP_PUBLIC_BASE_DOMAIN for cutover.",
                f"{host}{path_part} {{",
            ]
        )
        if protected:
            lines.extend(
                [
                    "    handle /caddy-schutz/* {",
                    "        reverse_proxy 127.0.0.1:8765",
                    "    }",
                    "    handle {",
                    "        import caddy_schutz_forward_auth",
                    f"        reverse_proxy {route.upstream}",
                    "    }",
                ]
            )
        else:
            lines.append(f"    reverse_proxy {route.upstream}")
        lines.extend(["}", ""])
    path = Path(settings.generated_caddy_dir) / "routes.caddy"
    checksum = _write(path, "\n".join(lines))
    artifact = models.GeneratedArtifact(artifact_type="caddy", path=str(path), checksum=checksum, status="generated")
    db.add(artifact)
    db.commit()
    return {"path": str(path), "checksum": checksum, "routes": len(routes)}


def export_json(db: Session) -> dict:
    settings = get_settings()
    services = db.query(models.Service).order_by(models.Service.slug).all()
    payload = []
    for service in services:
        payload.append(
            {
                "slug": service.slug,
                "title": service.title,
                "system": service.system,
                "component_type": service.component_type,
                "lifecycle": service.lifecycle,
                "owner": service.owner,
                "criticality": service.criticality,
                "tags": service.tags,
                "routes": [{"host": render_domain_value(r.host), "host_template": r.host, "path": r.path, "upstream": r.upstream, "tls": r.tls} for r in service.routes],
                "docs": [{"type": d.doc_type, "path": d.path, "title": d.title} for d in service.docs],
                "skills": [{"slug": s.slug, "type": s.skill_type, "path": s.path} for s in service.skills],
            }
        )
    path = Path(settings.selfhost_root) / "exports" / "control-plane-export.json"
    checksum = _write(path, json.dumps({"services": payload}, indent=2, sort_keys=True))
    db.add(models.ExportRun(export_type="json", path=str(path), status="created"))
    db.commit()
    return {"path": str(path), "checksum": checksum, "services": len(payload)}
